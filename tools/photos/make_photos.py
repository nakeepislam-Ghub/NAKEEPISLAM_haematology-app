"""Build src/photos.js from selections.json + downloaded images + candidate metadata.
selections: {cellId: {"label": thumb label, "box": [x0,y0,x1,y1] fractions (optional),
             "author": override, "caption": optional, "note": optional}}"""
import json, sys, io, base64
from PIL import Image
sel = json.load(open(sys.argv[1])); cands = json.load(open(sys.argv[2])); out = sys.argv[3]
LIC = {"Public domain": "Public domain", "CC0": "CC0"}
def norm_lic(l):
    l = l.strip()
    return LIC.get(l, l)
photos = {}
for cid, s in sel.items():
    meta = cands[s["label"]]
    import os
    if not os.path.exists("data/th/" + s["label"] + ".jpg"):
        print("MISSING", cid, file=sys.stderr); continue
    im = Image.open("data/th/" + s["label"] + ".jpg").convert("RGB")
    W, H = im.size
    x0, y0, x1, y1 = s.get("box", [0, 0, 1, 1])
    bx0, by0, bx1, by1 = x0 * W, y0 * H, x1 * W, y1 * H
    side = max(bx1 - bx0, by1 - by0); side = min(side, W, H)
    cx, cy = (bx0 + bx1) / 2, (by0 + by1) / 2
    l = min(max(cx - side / 2, 0), W - side); t = min(max(cy - side / 2, 0), H - side)
    crop = im.crop((round(l), round(t), round(l + side), round(t + side)))
    cropped = side < min(W, H) * 0.98 or W != H
    size = min(420, round(side))
    crop = crop.resize((size, size), Image.LANCZOS)
    buf = io.BytesIO(); crop.save(buf, "JPEG", quality=80, optimize=True, progressive=True)
    note = s.get("note") or ("cropped and resized" if cropped else "resized")
    photos[cid] = dict(src="data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode(),
        title=meta["title"].replace("File:", ""), author=s.get("author") or meta["artist"],
        licence=norm_lic(meta["lic"]), page=meta["page"], note=note, caption=s.get("caption", ""))
    print(cid, len(buf.getvalue()) // 1024, "KB", file=sys.stderr)
with open(out, "w") as f:
    f.write("/* Generated by tools/make_photos.py: openly licensed photomicrographs from Wikimedia Commons.\n   Each entry keeps its author, licence and source page; do not edit by hand. */\n")
    f.write("const PHOTOS = " + json.dumps(photos, ensure_ascii=False, indent=0) + ";\n")
